export function createTranslator(locale) {
  const column = locale === 'en' ? 1 : 0;
  return (key, values = {}) => {
    const message = messages[key]?.[column];
    if (message === undefined) throw new Error(`Missing interface message: ${key}`);
    return message.replace(/\{([a-z]+)\}/gi, (_, name) => {
      if (!Object.hasOwn(values, name)) throw new Error(`Missing value for ${key}.${name}`);
      return String(values[name]);
    });
  };
}
